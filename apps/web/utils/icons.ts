export function fileIconName(name: string, type: "file" | "directory"): IconName {
  if (type === "directory") return "folder";
  const extension = name.split(".").pop()?.toLowerCase() ?? "";
  if (["jar", "zip", "gz", "tar", "7z", "rar"].includes(extension)) return "archive";
  if (["json", "yml", "yaml", "toml", "properties", "conf", "cfg", "xml", "sh", "bat", "js", "ts", "py"].includes(extension)) return "fileCode";
  if (["png", "jpg", "jpeg", "gif", "webp", "svg", "ico"].includes(extension)) return "image";
  if (["mca", "mcr", "nbt", "dat"].includes(extension)) return "map";
  return "file";
}
